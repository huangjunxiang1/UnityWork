using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;
using YooAsset.Editor;

/// <summary>
/// 扫描 YooAsset 3.0 的收集器配置，提取所有资源的定位地址（Location），
/// 生成包含字符串常量的常量类。
/// - 非数字后缀的地址：生成 const string 字段，字段名 = 去 group 前缀后的地址（清理非法字符）
/// - 以 _数字(_数字)* 结尾的地址：不生成具体字段，改为生成参数化方法 FMT_前缀(object suffix)
///   例如 "model_Icon_1"（group=model）会生成 FMT_Icon(object suffix) => $"model_Icon_{suffix}"
/// 输出: Assets/Code/HotFix/_Gen/YooAssetLocations.cs
/// </summary>
public static class YooAssetLocationGenerator
{
    private const string OutputPath = "Assets/Code/HotFix/_Gen/AssetsID.cs";
    private const string MenuPath = "Tools/YooAsset Location Generator";
    private const string TopClassName = "AssetsID";
    private const string FormatPrefix = "fmt_";

    /// <summary>打开后会在 Console 输出每一步的扫描详情。</summary>
    private const bool VerboseLog = true;

    // 匹配末尾的 _数字(_数字)* 模式。
    // 例：Icon_1 -> prefix=Icon, numbers=1
    //     Icon_1_2_3 -> prefix=Icon, numbers=1_2_3
    private static readonly Regex NumericSuffixRegex = new Regex(
        @"^(?<prefix>.+?)_(?<numbers>\d+(?:_\d+)*)$",
        RegexOptions.Compiled);

    [MenuItem(MenuPath)]
    public static void Generate()
    {
        var setting = BundleCollectorSettingData.Setting;
        if (setting == null)
        {
            Debug.LogError("[YooAssetLocationGenerator] 找不到 BundleCollectorSettingData.Setting，请先配置 YooAsset 收集器。");
            return;
        }

        if (VerboseLog)
            Debug.Log($"[YooAssetLocationGenerator] 开始扫描: {setting.Packages.Count} 个 Package");

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     此文件由 YooAssetLocationGenerator 自动生成，请勿手动修改。");
        sb.AppendLine($"//     重新生成: {MenuPath}");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine($"public static class {TopClassName}");
        sb.AppendLine("{");

        int packageCount = 0;
        int groupCount = 0;
        int fieldCount = 0;
        int formatCount = 0;
        var usedPackageClasses = new HashSet<string>();

        foreach (var package in setting.Packages)
        {
            if (package == null || string.IsNullOrEmpty(package.PackageName)) continue;

            string packageClassName = SanitizeClassName(package.PackageName);
            if (string.IsNullOrEmpty(packageClassName)) continue;
            if (!usedPackageClasses.Add(packageClassName)) continue;

            sb.AppendLine($"    /// <summary>Package: {package.PackageName}</summary>");
            sb.AppendLine($"    public static class {packageClassName}");
            sb.AppendLine("    {");

            var usedGroupClasses = new HashSet<string>();

            foreach (var group in package.Groups)
            {
                if (group == null || string.IsNullOrEmpty(group.GroupName)) continue;

                string groupClassName = SanitizeClassName(group.GroupName);
                if (string.IsNullOrEmpty(groupClassName)) continue;
                if (!usedGroupClasses.Add(groupClassName)) continue;

                // ============================================================
                //  收集该 Group 下所有资源的定位地址
                // ============================================================
                var locations = new HashSet<string>();

                foreach (var collector in group.Collectors)
                {
                    if (collector == null) continue;

                    string collectPath = NormalizeAssetPath(collector.CollectPath);
                    if (string.IsNullOrEmpty(collectPath))
                    {
                        if (VerboseLog)
                            Debug.LogWarning($"[YooAssetLocationGenerator] [{package.PackageName}/{group.GroupName}] CollectPath 为空，跳过。");
                        continue;
                    }

                    IAddressRule addressRule = null;
                    try
                    {
                        addressRule = BundleCollectorSettingData.GetAddressRuleInstance(collector.AddressRuleName);
                    }
                    catch (System.Exception e)
                    {
                        if (VerboseLog)
                            Debug.LogWarning($"[YooAssetLocationGenerator] 获取寻址规则 '{collector.AddressRuleName}' 失败: {e.Message}");
                    }

                    var assetPaths = ScanCollectPath(collectPath, collector.FilterRuleName);

                    if (VerboseLog)
                        Debug.Log($"[YooAssetLocationGenerator] [{package.PackageName}/{group.GroupName}] CollectPath='{collectPath}' Rule='{collector.AddressRuleName}' -> 扫描到 {assetPaths.Count} 个资源");

                    foreach (var assetPath in assetPaths)
                    {
                        string location = ComputeLocation(addressRule, assetPath, collector, group);
                        if (string.IsNullOrEmpty(location))
                            location = Path.GetFileNameWithoutExtension(assetPath);

                        if (!string.IsNullOrEmpty(location))
                            locations.Add(location);
                    }
                }

                sb.AppendLine($"        /// <summary>Group: {group.GroupName}</summary>");
                sb.AppendLine($"        public static class {groupClassName}");
                sb.AppendLine("        {");

                // ============================================================
                //  分类：数字后缀 vs 普通地址
                //  字段名 / FMT 方法名去掉 group 前缀，拼接值仍用完整地址
                // ============================================================
                var sortedLocations = new List<string>(locations);
                sortedLocations.Sort(System.StringComparer.Ordinal);

                // group 前缀（用于剥离字段名，不影响地址值）
                string stripPrefix = group.GroupName + "_";

                // (完整地址, 字段短名)
                var fieldLocations = new List<(string value, string shortName)>();

                // (完整前缀, 短前缀) —— FMT 方法用短前缀做方法名，用完整前缀拼地址
                var fmtPrefixes = new List<(string valuePrefix, string shortPrefix)>();
                var fmtPrefixSet = new HashSet<string>();

                foreach (var loc in sortedLocations)
                {
                    // 剥离 group 前缀得到短名（仅用于字段名 / 方法名）
                    string shortName = StripGroupPrefix(loc, stripPrefix);

                    var m = NumericSuffixRegex.Match(shortName);
                    if (m.Success)
                    {
                        string shortPrefix = m.Groups["prefix"].Value;
                        if (string.IsNullOrEmpty(shortPrefix)) continue;
                        if (!fmtPrefixSet.Add(shortPrefix)) continue;

                        // 计算完整前缀：从 loc 里截取 shortPrefix 对应的位置
                        int offset = loc.Length - shortName.Length;
                        int fullPrefixLen = offset + shortPrefix.Length;
                        string valuePrefix = fullPrefixLen <= loc.Length
                            ? loc.Substring(0, fullPrefixLen)
                            : loc;

                        fmtPrefixes.Add((valuePrefix, shortPrefix));
                    }
                    else
                    {
                        fieldLocations.Add((loc, shortName));
                    }
                }

                // ---- 生成普通字段（字段名 = 去前缀后的短名） ----
                var seenMembers = new HashSet<string>();
                foreach (var (value, shortName) in fieldLocations)
                {
                    string fieldName = MakeIdentifier(shortName);
                    if (string.IsNullOrEmpty(fieldName)) continue;
                    if (!seenMembers.Add(fieldName)) continue;

                    sb.AppendLine($"            /// <summary>{value}</summary>");
                    sb.AppendLine($"            public const string {fieldName} = \"{value}\";");
                    fieldCount++;
                }

                // ---- 生成参数化方法（FMT_ + 去前缀短名） ----
                bool addedAnyFormat = false;
                foreach (var (valuePrefix, shortPrefix) in fmtPrefixes)
                {
                    string methodSuffix = MakeIdentifier(shortPrefix);
                    if (string.IsNullOrEmpty(methodSuffix)) continue;

                    string methodName = FormatPrefix + methodSuffix;
                    if (methodName == FormatPrefix) continue;
                    if (!seenMembers.Add(methodName)) continue;

                    if (!addedAnyFormat)
                    {
                        if (fieldLocations.Count > 0) sb.AppendLine();
                        addedAnyFormat = true;
                    }

                    sb.AppendLine($"            /// <summary>{valuePrefix}_&lt;suffix&gt;</summary>");
                    sb.AppendLine($"            public static string {methodName}(object suffix) => $\"{valuePrefix}_{{suffix}}\";");
                    formatCount++;
                }

                sb.AppendLine("        }");
                sb.AppendLine();

                groupCount++;
            }

            sb.AppendLine("    }");
            sb.AppendLine();
            packageCount++;
        }

        sb.AppendLine("}");

        // ================================================================
        //  写入文件
        // ================================================================
        var dir = Path.GetDirectoryName(OutputPath);
        if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
            Directory.CreateDirectory(dir);

        var newContent = sb.ToString();
        if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == newContent)
        {
            Debug.Log("[YooAssetLocationGenerator] 内容未变化，跳过生成。");
            return;
        }

        File.WriteAllText(OutputPath, newContent, new UTF8Encoding(false));
        AssetDatabase.Refresh();

        Debug.Log($"[YooAssetLocationGenerator] 生成完成: {packageCount} Package / {groupCount} Group / {fieldCount} 字段 / {formatCount} 参数化方法 -> {OutputPath}");

        if (fieldCount == 0 && formatCount == 0)
            Debug.LogWarning("[YooAssetLocationGenerator] 未生成任何内容。请根据上方扫描日志检查 CollectPath 是否有有效资源。");
    }

    // ================================================================
    //                       收集路径扫描
    // ================================================================

    private static List<string> ScanCollectPath(string collectPath, string filterRuleName)
    {
        var result = new List<string>();
        if (string.IsNullOrEmpty(collectPath)) return result;

        collectPath = collectPath.TrimEnd('/', '\\');

        string findAssetType = null;
        try
        {
            var filterRule = BundleCollectorSettingData.GetAssetFilterRuleInstance(filterRuleName);
            findAssetType = filterRule?.FindAssetType;
        }
        catch { /* 忽略 */ }

        string normalizedType = NormalizeFindAssetType(findAssetType);

        // 空字符串是 FindAssets 的合法输入，代表"匹配所有资源"
        var searchTypes = new List<string> { normalizedType };
        if (normalizedType != "") searchTypes.Add("");

        foreach (var searchType in searchTypes)
        {
            if (AssetDatabase.IsValidFolder(collectPath))
            {
                var guids = AssetDatabase.FindAssets(searchType, new[] { collectPath });
                foreach (var guid in guids)
                {
                    var path = AssetDatabase.GUIDToAssetPath(guid);
                    if (string.IsNullOrEmpty(path)) continue;
                    if (AssetDatabase.IsValidFolder(path)) continue;
                    result.Add(path);
                }
            }
            else
            {
                if (!string.IsNullOrEmpty(AssetDatabase.AssetPathToGUID(collectPath)))
                    result.Add(collectPath);
            }

            if (result.Count > 0) break;
        }

        result.Sort(System.StringComparer.Ordinal);
        return result;
    }

    private static string NormalizeFindAssetType(string raw)
    {
        if (string.IsNullOrEmpty(raw)) return "";

        string trimmed = raw.Trim();

        if (trimmed.Equals("all", System.StringComparison.OrdinalIgnoreCase))
            return "";

        if (trimmed.StartsWith("t:") || trimmed.StartsWith("l:") || trimmed.StartsWith("a:"))
            return trimmed;

        return "t:" + trimmed;
    }

    private static string NormalizeAssetPath(string path)
    {
        if (string.IsNullOrEmpty(path)) return null;
        return path.Replace('\\', '/').TrimEnd('/');
    }

    // ================================================================
    //                       地址计算
    // ================================================================

    private static string ComputeLocation(
        IAddressRule rule, string assetPath,
        BundleCollector collector, BundleCollectorGroup group)
    {
        if (rule == null) return null;

        try
        {
            var data = new AddressRuleData(assetPath, collector.CollectPath, group.GroupName, collector.UserData);
            return rule.GetAssetAddress(data);
        }
        catch
        {
            return null;
        }
    }

    // ================================================================
    //                          工具方法
    // ================================================================

    /// <summary>
    /// 去掉地址开头的 group 前缀。
    /// 例：group="model"，loc="model_Cube" -> "Cube"；
    ///     若 loc 不以该前缀开头，则原样返回。
    /// </summary>
    private static string StripGroupPrefix(string location, string groupPrefix)
    {
        if (string.IsNullOrEmpty(location)) return location;
        if (string.IsNullOrEmpty(groupPrefix)) return location;

        if (location.StartsWith(groupPrefix, System.StringComparison.Ordinal))
        {
            string stripped = location.Substring(groupPrefix.Length);
            // 全剥完就保留原值（避免生成空标识符）
            if (!string.IsNullOrEmpty(stripped)) return stripped;
        }

        return location;
    }

    /// <summary>
    /// 把字符串转换为合法 C# 标识符：非字母数字字符替换为下划线，
    /// 合并连续下划线，去掉首尾下划线；以数字开头时补下划线。
    /// </summary>
    private static string MakeIdentifier(string raw)
    {
        if (string.IsNullOrEmpty(raw)) return null;

        var sb = new StringBuilder(raw.Length);
        foreach (var c in raw)
            sb.Append(char.IsLetterOrDigit(c) ? c : '_');

        var result = Regex.Replace(sb.ToString(), "_+", "_").Trim('_');
        if (string.IsNullOrEmpty(result)) return null;
        if (char.IsDigit(result[0])) result = "_" + result;
        return result;
    }

    /// <summary>类名清理，与 MakeIdentifier 相同逻辑。</summary>
    private static string SanitizeClassName(string raw) => MakeIdentifier(raw);
}