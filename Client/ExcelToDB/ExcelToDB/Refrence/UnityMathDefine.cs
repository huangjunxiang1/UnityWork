using System;
using System.Collections.Generic;
using System.Text;

namespace Unity.Mathematics
{
    public struct float2
    {
        public float x;
        public float y;
        public float2(float x, float y)
        {
            this.x = x;
            this.y = y;
        }
    }
    public struct float3
    {
        public float x;
        public float y;
        public float z;
        public float3(float x, float y, float z)
        {
            this.x = x;
            this.y = y;
            this.z = z;
        }
    }
    public struct float4
    {
        public float x;
        public float y;
        public float z;
        public float w;
        public float4(float x, float y, float z, float w)
        {
            this.x = x;
            this.y = y;
            this.z = z;
            this.w = w;
        }
    }
    public struct int2
    {
        public int x;
        public int y;
        public int2(int x, int y)
        {
            this.x = x;
            this.y = y;
        }
    }
    public struct int3
    {
        public int x;
        public int y;
        public int z;
        public int3(int x, int y, int z)
        {
            this.x = x;
            this.y = y;
            this.z = z;
        }
    }
    public struct int4
    {
        public int x;
        public int y;
        public int z;
        public int w;
        public int4(int x, int y, int z, int w)
        {
            this.x = x;
            this.y = y;
            this.z = z;
            this.w = w;
        }
    }
}
